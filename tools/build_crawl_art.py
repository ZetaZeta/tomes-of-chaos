def wizards():
    """Copies the DCSS paper-doll layers a wizard can be made of into assets/sprites_crawl/wizlayers/ and writes
    src/ui/wizard_looks.gd (school -> robe, hat, staff, hand item).  Art composes them at runtime."""
    P = os.path.join(DCSS, "player")
    root = os.path.join(OUT, "wizlayers")
    shutil.rmtree(root, ignore_errors=True)
    def grab(sub, name, dest=None):
        if not name:
            return
        src = os.path.join(P, sub, name + ".png")
        if not os.path.exists(src):
            src = os.path.join(P, sub, "misc", name + ".png")
        os.makedirs(os.path.join(root, dest or sub), exist_ok=True)
        shutil.copy(src, os.path.join(root, dest or sub, name + ".png"))
    for robe, hat, staff, item in SCHOOL_LOOKS.values():
        grab("body", robe); grab("head", hat); grab("hand1", staff); grab("hand2", item)
    for b in WIZ_BASES:
        grab("base", b)
    for be in WIZ_BEARDS:
        grab("beard", be)
    lines = ["# GENERATED by tools/build_crawl_art.py - do not edit", "class_name WizardLooks", "extends RefCounted", "",
             "const SCHOOLS := {"]
    for k, v in SCHOOL_LOOKS.items():
        lines.append('\t"%s": ["%s", "%s", "%s", "%s"],' % ((k,) + v))
    lines += ["}", "const BASES := %s" % json.dumps(WIZ_BASES), "const BEARDS := %s" % json.dumps(WIZ_BEARDS), ""]
    open(os.path.join(os.path.dirname(__file__), "..", "src", "ui", "wizard_looks.gd"), "w").write("\n".join(lines))
    print("wizard layers", len(SCHOOL_LOOKS), "looks")

